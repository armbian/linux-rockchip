#define CROP_START(SRC, DST) (((SRC) - (DST)) / 2 / 4 * 4)
#define DST_WIDTH 4608
#define DST_HEIGHT 3456
/*
 * The resolution of the driver configuration needs to be exactly
 * the same as the current output resolution of the sensor,
 * the input width of the isp needs to be 16 aligned,
 * the input height of the isp needs to be 8 aligned.
 * Can be cropped to standard resolution by this function,
 * otherwise it will crop out strange resolution according
 * to the alignment rules.
 */
static int ov32b40_get_selection(struct v4l2_subdev *sd,
	struct v4l2_subdev_state *sd_state,
	struct v4l2_subdev_selection *sel)
{
	struct ov32b40 *ov32b40 = to_ov32b40(sd);

	if (sel->target == V4L2_SEL_TGT_CROP_BOUNDS) {
		if (ov32b40->cur_mode->width == 4672) {
			sel->r.left = CROP_START(ov32b40->cur_mode->width, DST_WIDTH);
			sel->r.width = DST_WIDTH;
			sel->r.top = CROP_START(ov32b40->cur_mode->height, DST_HEIGHT);
			sel->r.height = DST_HEIGHT;
		} else {
			sel->r.left = 0;
			sel->r.width = ov32b40->cur_mode->width;
			sel->r.top = 0;
			sel->r.height = ov32b40->cur_mode->height;
		}
		return 0;
	}

	return -EINVAL;
}

