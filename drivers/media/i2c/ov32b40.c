static long ov32b40_ioctl(struct v4l2_subdev *sd, unsigned int cmd, void *arg)
{
	struct ov32b40 *ov32b40 = to_ov32b40(sd);
	struct rkmodule_hdr_cfg *hdr_cfg;
	long ret = 0;
	u32 i, h, w;
	u32 stream = 0;

	switch (cmd) {
	case RKMODULE_SET_HDR_CFG:
		hdr_cfg = (struct rkmodule_hdr_cfg *)arg;
		w = ov32b40->cur_mode->width;
		h = ov32b40->cur_mode->height;
		for (i = 0; i < ov32b40->cfg_num; i++) {
			if (w == supported_modes[i].width &&
			h == supported_modes[i].height &&
			supported_modes[i].hdr_mode == hdr_cfg->hdr_mode) {
				ov32b40->cur_mode = &supported_modes[i];
				break;
			}
		}
		if (i == ov32b40->cfg_num) {
			dev_err(&ov32b40->client->dev,
				"not find hdr mode:%d %dx%d config\n",
				hdr_cfg->hdr_mode, w, h);
			ret = -EINVAL;
		} else {
			w = ov32b40->cur_mode->hts_def - ov32b40->cur_mode->width;
			h = ov32b40->cur_mode->vts_def - ov32b40->cur_mode->height;
			mutex_lock(&ov32b40->mutex);
			__v4l2_ctrl_modify_range(ov32b40->hblank, w, w, 1, w);
			__v4l2_ctrl_modify_range(ov32b40->vblank, h,
						 OV32B40_VTS_MAX - ov32b40->cur_mode->height,
						 1, h);
			mutex_unlock(&ov32b40->mutex);
			dev_info(&ov32b40->client->dev,
				"sensor mode: %d\n",
				ov32b40->cur_mode->hdr_mode);
		}
		break;
	case RKMODULE_GET_HDR_CFG:
		hdr_cfg = (struct rkmodule_hdr_cfg *)arg;
		hdr_cfg->esp.mode = HDR_NORMAL_VC;
		hdr_cfg->hdr_mode = ov32b40->cur_mode->hdr_mode;
		break;
	case RKMODULE_GET_MODULE_INFO:
		ov32b40_get_module_inf(ov32b40, (struct rkmodule_inf *)arg);
		break;
	case RKMODULE_SET_QUICK_STREAM:

		stream = *((u32 *)arg);

		if (stream)
			ret = ov32b40_write_reg(ov32b40->client,
				 OV32B40_REG_CTRL_MODE,
				 OV32B40_REG_VALUE_08BIT,
				 OV32B40_MODE_STREAMING);
		else
			ret = ov32b40_write_reg(ov32b40->client,
				 OV32B40_REG_CTRL_MODE,
				 OV32B40_REG_VALUE_08BIT,
				 OV32B40_MODE_SW_STANDBY);
		break;
	default:
		ret = -ENOIOCTLCMD;
		break;
	}

	return ret;
}

