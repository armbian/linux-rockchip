static int __ov32b40_start_stream(struct ov32b40 *ov32b40)
{
	int ret;

	ret = ov32b40_write_array(ov32b40->client, ov32b40_global_regs);
	if (ret) {
		dev_err(&ov32b40->client->dev, "%s: global reg write error!\n", __func__);
		return ret;
	}

	ret = ov32b40_write_array(ov32b40->client, ov32b40->cur_mode->reg_list);
	if (ret)
		return ret;
	dev_info(&ov32b40->client->dev, "%s: init register write done!\n", __func__);

	/* In case these controls are set before streaming */
	mutex_unlock(&ov32b40->mutex);
	ret = v4l2_ctrl_handler_setup(&ov32b40->ctrl_handler);
	mutex_lock(&ov32b40->mutex);
	if (ret)
		return ret;

	return ov32b40_write_reg(ov32b40->client,
				 OV32B40_REG_CTRL_MODE,
				 OV32B40_REG_VALUE_08BIT,
				 OV32B40_MODE_STREAMING);
}

static int __ov32b40_stop_stream(struct ov32b40 *ov32b40)
{
	return ov32b40_write_reg(ov32b40->client,
				 OV32B40_REG_CTRL_MODE,
				 OV32B40_REG_VALUE_08BIT,
				 OV32B40_MODE_SW_STANDBY);
}

static int ov32b40_s_stream(struct v4l2_subdev *sd, int on)
{
	struct ov32b40 *ov32b40 = to_ov32b40(sd);
	struct i2c_client *client = ov32b40->client;
	int ret = 0;

	dev_info(&client->dev, "%s: on: %d, %dx%d@%d\n", __func__, on,
				ov32b40->cur_mode->width,
				ov32b40->cur_mode->height,
		DIV_ROUND_CLOSEST(ov32b40->cur_mode->max_fps.denominator,
				  ov32b40->cur_mode->max_fps.numerator));

	mutex_lock(&ov32b40->mutex);
	on = !!on;
	if (on == ov32b40->streaming)
		goto unlock_and_return;

	if (on) {
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		ret = __ov32b40_start_stream(ov32b40);
		if (ret) {
			v4l2_err(sd, "start stream failed while write regs\n");
			pm_runtime_put(&client->dev);
			goto unlock_and_return;
		}
	} else {
		__ov32b40_stop_stream(ov32b40);
		pm_runtime_put(&client->dev);
	}

	ov32b40->streaming = on;

unlock_and_return:
	mutex_unlock(&ov32b40->mutex);

	return ret;
}

static int ov32b40_s_power(struct v4l2_subdev *sd, int on)
{
	struct ov32b40 *ov32b40 = to_ov32b40(sd);
	struct i2c_client *client = ov32b40->client;
	int ret = 0;

	dev_info(&client->dev, "%s(%d) on(%d)\n", __func__, __LINE__, on);

	mutex_lock(&ov32b40->mutex);

	/* If the power state is not modified - no work to do. */
	if (ov32b40->power_on == !!on)
		goto unlock_and_return;

	if (on) {
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		ov32b40->power_on = true;
	} else {
		pm_runtime_put(&client->dev);
		ov32b40->power_on = false;
	}

unlock_and_return:
	mutex_unlock(&ov32b40->mutex);

	return ret;
}

/* Calculate the delay in us by clock rate and clock cycles */
static inline u32 ov32b40_cal_delay(u32 cycles)
{
	return DIV_ROUND_UP(cycles, OV32B40_XVCLK_FREQ / 1000 / 1000);
}

static int __ov32b40_power_on(struct ov32b40 *ov32b40)
{
	int ret;
	u32 delay_us;
	struct device *dev = &ov32b40->client->dev;

	if (!IS_ERR(ov32b40->power_gpio))
		gpiod_set_value_cansleep(ov32b40->power_gpio, 1);

	usleep_range(1000, 2000);

	if (!IS_ERR_OR_NULL(ov32b40->pins_default)) {
		ret = pinctrl_select_state(ov32b40->pinctrl,
					   ov32b40->pins_default);
		if (ret < 0)
			dev_err(dev, "could not set pins\n");
	}
	ret = clk_set_rate(ov32b40->xvclk, OV32B40_XVCLK_FREQ);
	if (ret < 0)
		dev_warn(dev, "Failed to set xvclk rate (24MHz)\n");
	if (clk_get_rate(ov32b40->xvclk) != OV32B40_XVCLK_FREQ)
		dev_warn(dev, "xvclk mismatched, modes are based on 24MHz\n");
	ret = clk_prepare_enable(ov32b40->xvclk);
	if (ret < 0) {
		dev_err(dev, "Failed to enable xvclk\n");
		return ret;
	}
	if (!IS_ERR(ov32b40->reset_gpio))
		gpiod_set_value_cansleep(ov32b40->reset_gpio, 0);

	ret = regulator_bulk_enable(OV32B40_NUM_SUPPLIES, ov32b40->supplies);
	if (ret < 0) {
		dev_err(dev, "Failed to enable regulators\n");
		goto disable_clk;
	}

	if (!IS_ERR(ov32b40->reset_gpio))
		gpiod_set_value_cansleep(ov32b40->reset_gpio, 1);

	usleep_range(5000, 6000);
	if (!IS_ERR(ov32b40->pwdn_gpio))
		gpiod_set_value_cansleep(ov32b40->pwdn_gpio, 1);

	/* 8192 cycles prior to first SCCB transaction */
	delay_us = ov32b40_cal_delay(8192);
	usleep_range(delay_us * 2, delay_us * 3);

	return 0;

disable_clk:
	clk_disable_unprepare(ov32b40->xvclk);

	return ret;
}

static void __ov32b40_power_off(struct ov32b40 *ov32b40)
{
	int ret;
	struct device *dev = &ov32b40->client->dev;

	if (!IS_ERR(ov32b40->pwdn_gpio))
		gpiod_set_value_cansleep(ov32b40->pwdn_gpio, 0);
	clk_disable_unprepare(ov32b40->xvclk);
	if (!IS_ERR(ov32b40->reset_gpio))
		gpiod_set_value_cansleep(ov32b40->reset_gpio, 0);

	if (!IS_ERR_OR_NULL(ov32b40->pins_sleep)) {
		ret = pinctrl_select_state(ov32b40->pinctrl,
					   ov32b40->pins_sleep);
		if (ret < 0)
			dev_dbg(dev, "could not set pins\n");
	}
	if (!IS_ERR(ov32b40->power_gpio))
		gpiod_set_value_cansleep(ov32b40->power_gpio, 0);

	regulator_bulk_disable(OV32B40_NUM_SUPPLIES, ov32b40->supplies);
}

static int ov32b40_runtime_resume(struct device *dev)
{
	struct i2c_client *client = to_i2c_client(dev);
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct ov32b40 *ov32b40 = to_ov32b40(sd);

	return __ov32b40_power_on(ov32b40);
}

static int ov32b40_runtime_suspend(struct device *dev)
{
	struct i2c_client *client = to_i2c_client(dev);
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct ov32b40 *ov32b40 = to_ov32b40(sd);

	__ov32b40_power_off(ov32b40);

	return 0;
}

